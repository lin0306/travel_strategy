/**
 * 「当前正在看哪座城市」—— 从**导航状态**认。
 *
 * ## 为什么需要它（而不是 `useNavCityId()` 直接用）
 * 它是全站统一的「我在哪个城市」入口（顶栏、规划面板、添加行程选择器都用它）。
 * 保留这一层是为了让**判据只有一处**：哪天城市上下文的定义要变（比如行程页
 * 允许"跨城"），只改这里。
 *
 * ## 2026-11-18：判据从 URL 换成 `navStore`
 * 原来按 `/city/([^/]+)` 正则从 pathname 抠。现在路径恒为 `/`，那条正则
 * 永远匹配不到 —— 不改的话，规划面板会以为"任何页面都没有城市"，
 * 新建规划直接禁用（**不报错**，只是按钮哑掉）。
 *
 * ⚠️ 首页与省级页确实**没有**城市 —— 返回 `null` 是正确答案，
 *    调用方要按"没有城市上下文"处理，而不是随便挑一座城。
 */

import { useNavCityId } from '~/common/logic/nav/navStore'

export function useCurrentCityId(): string | null {
  return useNavCityId()
}
