/**
 * 地图**覆盖物图层的 zIndex** —— 唯一出处。
 *
 * ## 为什么必须收成一张表
 * 这些数字原来散在四个图层文件里（`8 / 9 / 20 / 21 / 22 / 24 / 30 / 31 / 32`），
 * 于是"谁压谁"要翻四个文件才能拼出来。而**层级错的表现是"某个东西看不见了"** ——
 * 不报错、不影响类型检查、截图里也未必一眼看出来，是最容易长期潜伏的那种问题。
 *
 * ## 顺序（数字越大越靠上）
 *
 * | zIndex | 层 | 为什么在这个位置 |
 * |-------:|----|----------------|
 * | 8 | 区的**面** | 纯衬托，垫在所有东西下面 |
 * | 9 | 区徽标 | 压在自己那片面上 |
 * | 20 | POI 圆点 / 聚合点 | 应用层的第一档 |
 * | 21 | POI 名字 | 名字不能压在自己的圆点上 |
 * | 22 | POI 选中态（白底座） | 白底座不该被任何文字盖住 |
 * | 24 | 通用标记层（默认档） | 高于 POI、低于路线 |
 * | 30 | 路线：背景整条线 + **待选**候选 | — |
 * | 31 | 路线：**选中的那条** | 压在候选之上（不靠 geometry 顺序赌） |
 * | 32 | 路线：拥堵细线 | 压在选中的那条之上 |
 * | 33 | 路线：**换乘点** | 压在整条路线之上才看得见 |
 * | 34 | 序号 / 住宿标记 | 应用层最上一档；**必须在路线之上**，否则序号被线穿过 |
 *
 * ## ⚠️ 这里曾经有一个真 bug
 * `usePlanMapLayers` 给序号标记的是 **24**，而路线是 **30/31** ——
 * **标记低于路线 ⇒ 序号被路线盖住**。它在"完整行程页"上一直存在，
 * 只是路线不经过标记时不显眼。现已统一到 `planMarker`。
 *
 * ★ 腾讯的 `MultiPolyline` **不保证**同一图层内后加入的 geometry 盖在先加入之上，
 *   所以"谁压谁"只能靠 zIndex（结构保证），不能靠数组顺序 —— 这一点在
 *   `routeLayer.ts` 拆出 `base` / `focus` / `jam` 三层时已经吃过一次教训。
 */
