/**
 * 「**未选中**」的配色 —— 出行方式按钮、公共交通的优先选项、方案列表的每一行。
 *
 * ## ★★ 两轮反馈，最后落在这里（看着矛盾，其实不是）
 * 用户 2026-10-05：
 * ① 「不要用灰色表示待选，都看不出来，**用浅蓝色**」
 *    → 那说的是**地图上那条灰线**：它叠在浅灰路网上跟路网一个色系，
 *      确实"跟没画一样"。⇒ 地图线改浅蓝（在 `map/tencent/routeStyles.ts`）。
 * ② 「选中高亮和没选中的颜色**差不多**，得调整一下**没选中的颜色用灰色**」
 *    → 这次说的是**这些按钮**。上一轮把它们一起改成了浅蓝，
 *      于是"浅蓝未选中"和"主蓝选中"只差一档明度，分不清哪个是选中的。
 *
 * ⇒ **两个介质、两个问题**：
 * | 在哪 | 未选中用什么 | 为什么 |
 * |---|---|---|
 * | 地图上的线 | **浅蓝** | 灰的叠在路网底图上跟没画一样 |
 * | UI 里的按钮 / 行 | **灰** | 浅蓝的和选中的主蓝太像 |
 *
 * ## 选中态怎么和它对开
 * 不靠"比灰更深的什么颜色"，靠**底色**：选中 = 主色边框 + 主色文字 + **淡蓝底**。
 * 底色是这里最有效的一维 —— 它不参与"深浅"的比较，扫一眼就能看见。
 */
export const PENDING_CLS = 'border-line text-ink-2'

/**
 * **选中**态的边框与文字 —— 底色由调用方补（有的地方整块是按钮、有的只是一枚圆点）。
 * 与 `PENDING_CLS` 成对：改一个就该看一眼另一个。
 */
export const PICKED_CLS = 'border-primary text-primary'

/** 选中态用的**淡蓝底** —— 「选中」与「未选中」最主要的区分手段（见文件头） */
