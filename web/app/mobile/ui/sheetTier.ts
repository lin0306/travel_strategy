/**
 * 底部浮层的**尺寸模型**（唯一出处）—— 三档吸附 **与** 自由拉伸两种。
 *
 * 为什么单独一个文件：`Sheet.tsx`（版式）与 `useSheetDrag.ts`（手势）都要读这几个值，
 * 而两者是**互相依赖**的 —— 手势要判档位、版式要用手势。常量放在第三方，
 * 两边各自 import，就没有环。
 *
 * ## 两种尺寸模式
 * | 模式 | 用在 | 尺寸 |
 * |------|------|------|
 * | **三档**（`tier`） | 城市清单 / 景点详情 / 路线规划 | `peek 28 / half 56 / full 88`（svh），松手吸附 |
 * | **自由**（`size`） | 图层设置 | 用户拖到哪停哪，只夹在 `min..max` 之间 |
 *
 * ★ 2026-10-28 用户对图层浮层定的：「不做固定三个大小，改成用户默认拉，限制最大高度和
 *   最小高度」。内容块（标题 + 6 行开关）高度本来就固定，三档里有两档都用不上 ——
 *   而"自由拉"对这类短表单反而更顺手：想露多少地图就拉多少。
 *
 * ★ 高度用 `svh` 不用 `vh`：移动端 `100vh` 把地址栏算在内，实际比可视区高 56–80px，
 *   `full` 档的底部会被推出屏幕。
 */

export type SheetTier = 'peek' | 'half' | 'full'

/** 档位顺序（低 → 高） */
export const SHEET_ORDER: SheetTier[] = ['peek', 'half', 'full']

/** 三档高度（svh）。数值与 08 文档一致 */
export const SHEET_TIER_SVH: Record<SheetTier, number> = { peek: 28, half: 56, full: 88 }

/** 拖到最矮也留这么高（把手 + 一行摘要），否则浮层会缩成一条缝 */
export const MIN_DRAG_PX = 72

/**
 * 自由拉伸模式的上下限与初始高度（svh）。
 *
 * `min` 取 34 而不是更小：再矮连"底图 / 影像图"两条都露不全，拉起来像卡住了。
 * `max` 与 `full` 档对齐（88），不然两种浮层贴顶时的观感不一致。
 * `initial` 与原来的 `half` 相同 —— 用户第一次点开看到的画面不变。
 */
export const SHEET_FREE_SVH = { min: 34, max: 88, initial: 56 }
